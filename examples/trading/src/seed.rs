    /// The phrase every BIP-39 implementation tests against, at the entropy
    /// size it is usually written at.
    const ZEROS: &str = "abandon abandon abandon abandon abandon abandon abandon abandon abandon \
                         abandon abandon about";

    fn hex(bytes: &[u8]) -> String {
        bytes.iter().map(|byte| format!("{byte:02x}")).collect()
    }

    fn seed(phrase: &str, passphrase: &str) -> Seed {
        seed_from_phrase(phrase, passphrase).expect("a phrase from the vectors")
    }

    /// The wordlist is data, so it is checked as data.
    ///
    /// A single corrupted word compiles, parses, and derives a wrong account
    /// for exactly the phrases containing it — an owner would see an empty
    /// account and no reason for it. The digest is the official list's, which
    /// is published and widely quoted.
    #[test]
    fn the_wordlist_is_the_official_one() {
        assert_eq!(
            hex(&Sha256::digest(WORDLIST.as_bytes())),
            "2f5eed53a4727b4bf8880d8f3f199efc90e58503646d9ff8eff3a2ed3b24dbda",
        );
        let words: Vec<&str> = WORDLIST.lines().collect();
        assert_eq!(words.len(), 2_048, "eleven bits per word, exactly");
        assert_eq!((words[0], words[2_047]), ("abandon", "zoo"));
        // Sorted, which is what makes the list searchable and is a property of
        // the official one rather than of any list of 2048 words.
        assert!(words.windows(2).all(|pair| pair[0] < pair[1]));
    }

