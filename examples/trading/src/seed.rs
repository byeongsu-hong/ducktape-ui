    /// A phrase that is wrong is refused, rather than deriving somebody's empty
    /// account.
    ///
    /// The checksum is what makes this possible at all: a wordlist alone says a
    /// phrase is *made of words*, and the last word's bits say it is *this*
    /// phrase. Without the check, one wrong word is an account the owner has
    /// never seen, with nothing on screen to say so.
    #[test]
    fn a_mistyped_phrase_is_refused_rather_than_derived() {
        // One word swapped for another real word: every word is in the list, and
        // the checksum is not.
        let swapped = ZEROS.replacen("abandon", "ability", 1);
        assert_eq!(
            seed_from_phrase(&swapped, "").unwrap_err(),
            SeedError::Checksum
        );
        // Two real words transposed, which is the other way a careful person
        // gets it wrong.
        assert_eq!(
            seed_from_phrase(
                "legal winner thank year wave sausage worth useful legal winner yellow thank",
                ""
            )
            .unwrap_err(),
            SeedError::Checksum,
        );
        // A word that is not a word, named by position so the message can point
        // at it without quoting the phrase.
        assert_eq!(
            seed_from_phrase(&ZEROS.replacen("abandon", "abandonn", 1), "").unwrap_err(),
            SeedError::UnknownWord(0),
        );
        // And a phrase of the wrong length, which no checksum can rescue.
        for wrong in ["abandon abandon about", ""] {
            assert_eq!(
                seed_from_phrase(wrong, "").unwrap_err(),
                SeedError::WordCount
            );
        }
        // The one that must still work.
        assert!(seed_from_phrase(ZEROS, "").is_ok());
    }

    /// A passphrase this module will not normalise is refused rather than
    /// stretched as its bytes happen to fall.
    ///
    /// BIP-39 says NFKD, and two spellings of the same accented passphrase are
    /// the same passphrase to a wallet that normalises and two different
    /// accounts to one that does not. Refusing is the honest half of not
    /// carrying a Unicode table.
    #[test]
    fn a_passphrase_this_cannot_normalise_is_refused() {
        assert_eq!(
            seed_from_phrase(ZEROS, "café").unwrap_err(),
            SeedError::Passphrase
        );
        assert!(seed_from_phrase(ZEROS, "cafe").is_ok());
        assert!(
            SeedError::Passphrase.message().contains("ASCII"),
            "the refusal says what would be accepted"
        );
    }

    /// Nothing that can be printed may carry the phrase or the seed.
    ///
    /// The rule `lighter_sign.rs` states for its key, applied to the one secret
    /// in this app that cannot be replaced: a leaked agent key trades badly for
    /// a while, a leaked recovery phrase is the account.
    #[test]
    fn no_printable_path_carries_the_phrase_or_the_seed() {
        let held = seed(ZEROS, "");
        assert_eq!(format!("{held:?}"), "Seed(<redacted>)");

        let mut printed = vec![format!("{held:?}")];
        for error in [
            SeedError::WordCount,
            SeedError::UnknownWord(3),
            SeedError::Checksum,
            SeedError::Passphrase,
            SeedError::Derivation,
        ] {
            printed.push(error.message());
            printed.push(format!("{error:?}"));
        }
        for text in printed {
            assert!(!text.contains("abandon"), "leaked a word: {text}");
            assert!(!text.contains("5eb00bbd"), "leaked the seed: {text}");
        }
    }

    fn hex_bytes(text: &str) -> Vec<u8> {
        (0..text.len() / 2)
            .map(|at| u8::from_str_radix(&text[at * 2..at * 2 + 2], 16).expect("hex"))
            .collect()
    }
