//! From a seed phrase to the one key an account owner actually holds.
//!
//! Every other key in this app is one it made for itself: an agent wallet, an
//! API key, both disposable and both approved by something else. This module
//! is the something else — the account's own key, the one that authorises an
//! enrolment and the one whose loss is not recoverable. It is the most
//! dangerous code in the tree, and it is written to be checkable rather than
//! clever.
//!
//! ## What is implemented, and against what
//!
//! BIP-39 (phrase to seed) and BIP-32 (seed to key along a path), hand-written
//! on `hmac`, `sha2` and `k256`, which were already in the lockfile. The house
//! rule for anything cryptographic applies and is the whole reason this is
//! acceptable to hand-write: **nothing here is checked against itself.**
//!
//! * BIP-39 against the Trezor vectors — the reference implementation's own —
//!   at all three entropy sizes, with and without a passphrase.
//! * BIP-32 against the spec's published test vectors, over a chain that mixes
//!   hardened and normal derivation.
//! * The whole path, phrase to Ethereum address, against pairs generated by a
//!   real **ethers.js v6.17.0** run. How they were made is recorded beside them
//!   so anyone can make them again.
//!
//! The two oracles cross-check: ethers' seed for `abandon…about` under the
//! passphrase `TREZOR` is byte-for-byte the Trezor vector's, which is a thing
//! neither project copied from the other.
//!
//! ## What is deliberately refused
//!
//! * **A non-ASCII passphrase.** BIP-39 says to NFKD-normalise the phrase and
//!   the passphrase before stretching them. For English words and an ASCII
//!   passphrase that is the identity, so this implements it by *refusing*
//!   anything else rather than by pulling in a Unicode normalisation table to
//!   be right about a case the app can decline. A passphrase this cannot
//!   normalise is a different seed silently, which is the one failure a seed
//!   phrase must never have.
//! * **A phrase whose checksum does not hold.** A mistyped word usually breaks
//!   it, and a broken checksum is caught here rather than discovered as an
//!   account that is empty for no visible reason.
//!
//! ## What is not defended against
//!
//! The bytes live in this process while a phrase is being imported, and Rust
//! cannot promise where the optimiser put a copy. Every buffer this module
//! *names* is wiped; see `Drop` on `PrivateKey` in `lighter_sign.rs` for the
//! same statement made at greater length. The mitigation that actually holds is
//! upstream of this file: the phrase is asked for once, converted, and handed
//! to the platform keychain, and the app never asks for it again.

// Complete and held to its oracles, and pointed at by nothing until the
// custody panel can take a phrase — the shape `signing.rs`, `lighter_sign.rs`
// and the order path each landed in first. Built and proven before a field can
// reach it, rather than arriving in the same change as the field that spends
// somebody's account.
#![allow(dead_code)]

use hmac::{Hmac, Mac};
use sha2::{Digest, Sha256, Sha512};

use crate::hyperliquid::HlError;

/// The official BIP-39 English wordlist, verbatim.
///
/// Data rather than code, and checked as data: `the_wordlist_is_the_official_one`
/// hashes it. A single corrupted word would not fail to compile, would not fail
/// to parse, and would derive a wrong account for exactly the phrases that
/// contain it — so the file is pinned by digest and not by eye.
const WORDLIST: &str = include_str!("bip39-english.txt");

/// PBKDF2's round count for BIP-39. Not a tuning knob: the spec says 2048 and a
/// different number is a different seed.
const STRETCH_ROUNDS: u32 = 2_048;

/// What a phrase can be wrong in.
///
/// Never carries the phrase, or any part of it, for the reason `SignError`
/// never carries a key: a message about a secret has a way of reaching a log.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SeedError {
    /// Not 12, 15, 18, 21 or 24 words.
    WordCount,
    /// A word that is not in the list. Named as a position so a reader can find
    /// it without the message quoting it.
    UnknownWord(usize),
    /// The words are all real and their checksum does not hold, which is what a
    /// mistyped or transposed word usually looks like.
    Checksum,
    /// A passphrase this module will not normalise. See the header.
    Passphrase,
    /// The path reached a child that is not a usable key. Astronomically
    /// unlikely and not ignorable: the spec says to skip to the next index, and
    /// pretending it cannot happen is how a wrong key gets derived.
    Derivation,
}

impl SeedError {
    /// What the panel says. The phrase never appears in it.
    pub fn message(self) -> String {
        match self {
            SeedError::WordCount => "A recovery phrase is 12, 15, 18, 21 or 24 words.".to_owned(),
            SeedError::UnknownWord(at) => {
                format!("Word {} is not a recovery-phrase word.", at + 1)
            }
            SeedError::Checksum => "That phrase does not check out — a word is wrong or two are \
                                    swapped. Nothing was stored."
                .to_owned(),
            SeedError::Passphrase => "The passphrase has to be plain ASCII here.".to_owned(),
            SeedError::Derivation => {
                "That phrase does not derive a usable key on this path.".to_owned()
            }
        }
    }
}

impl From<SeedError> for HlError {
    fn from(error: SeedError) -> Self {
        HlError::new(error.message())
    }
}

/// The 64-byte seed a phrase stretches into.
///
/// Wrapped rather than a bare array so it cannot be printed, cloned about, or
/// passed where a public value is expected. It is wiped on the way out.
pub struct Seed([u8; 64]);

impl Drop for Seed {
    fn drop(&mut self) {
        self.0.fill(0);
        std::hint::black_box(&mut self.0);
    }
}

impl std::fmt::Debug for Seed {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.write_str("Seed(<redacted>)")
    }
}

impl Seed {
    /// The bytes, for the one caller that derives from them.
    fn bytes(&self) -> &[u8; 64] {
        &self.0
    }
}

/// Stretch a recovery phrase into its seed.
///
/// The phrase is validated first — every word in the list, and the checksum the
/// last word carries — so a mistyped phrase is refused here rather than
/// silently deriving somebody else's empty account.
///
/// Whitespace is forgiving because a phrase gets pasted: any run of spaces,
/// tabs or newlines separates words, and the case is folded, because a wallet
/// that printed the phrase in capitals wrote the same phrase.
pub fn seed_from_phrase(phrase: &str, passphrase: &str) -> Result<Seed, SeedError> {
    if !passphrase.is_ascii() {
        return Err(SeedError::Passphrase);
    }
    let words: Vec<String> = phrase
        .split_whitespace()
        .map(|word| word.to_lowercase())
        .collect();
    check_phrase(&words)?;

    // The spec stretches the phrase in its canonical spelling — single spaces,
    // lower case — rather than however it was typed.
    let mut canonical = words.join(" ").into_bytes();
    let mut salt = format!("mnemonic{passphrase}").into_bytes();
    let seed = Seed(stretch(&canonical, &salt));
    canonical.fill(0);
    salt.fill(0);
    std::hint::black_box((&mut canonical, &mut salt));
    Ok(seed)
}

/// Every word in the list, and the checksum the phrase carries.
///
/// The checksum is what a wordlist alone cannot give: eleven bits per word, of
/// which the last few are a hash of the rest, so a single wrong word fails with
/// probability about 1 - 2^-4 at twelve words and better at longer ones. It is
/// the difference between "this is a phrase" and "this is *the* phrase".
fn check_phrase(words: &[String]) -> Result<(), SeedError> {
    if !matches!(words.len(), 12 | 15 | 18 | 21 | 24) {
        return Err(SeedError::WordCount);
    }
    let mut bits: Vec<bool> = Vec::with_capacity(words.len() * 11);
    for (at, word) in words.iter().enumerate() {
        let index = index_of(word).ok_or(SeedError::UnknownWord(at))?;
        for shift in (0..11).rev() {
            bits.push(index >> shift & 1 == 1);
        }
    }
    // The last len/32 bits are the checksum; everything before them is the
    // entropy the phrase encodes.
    let checksum_bits = bits.len() / 33;
    let entropy_bits = bits.len() - checksum_bits;
    let mut entropy = vec![0u8; entropy_bits / 8];
    for (at, bit) in bits[..entropy_bits].iter().enumerate() {
        if *bit {
            entropy[at / 8] |= 1 << (7 - at % 8);
        }
    }
    let digest = Sha256::digest(&entropy);
    let held = bits[entropy_bits..]
        .iter()
        .enumerate()
        .all(|(at, bit)| (digest[at / 8] >> (7 - at % 8) & 1 == 1) == *bit);
    entropy.fill(0);
    std::hint::black_box(&mut entropy);
    held.then_some(()).ok_or(SeedError::Checksum)
}

/// A word's position in the list, or nothing.
///
/// Linear over 2048 short strings, once per word, on a path a person reaches by
/// typing a phrase.
///
/// ponytail: a map would turn 2048 comparisons into one hash and is not worth
/// the static; if this ever runs anywhere but an import, build one.
fn index_of(word: &str) -> Option<u16> {
    WORDLIST
        .lines()
        .position(|listed| listed == word)
        .map(|at| at as u16)
}

/// PBKDF2-HMAC-SHA512, only as much of it as one 64-byte block needs.
///
/// Written out because that is twelve lines over the HMAC already in the tree,
/// against a dependency whose whole job is those twelve lines. The single block
/// is not a shortcut: the output is exactly one SHA-512 wide, so the block loop
/// a general implementation carries would run once.
fn stretch(password: &[u8], salt: &[u8]) -> [u8; 64] {
    let mut salted = salt.to_vec();
    // Block index 1, big-endian, which is the whole of PBKDF2's block counter
    // for an output this size.
    salted.extend_from_slice(&1u32.to_be_bytes());
    let mut current = hmac_sha512(password, &salted);
    let mut out = current;
    for _ in 1..STRETCH_ROUNDS {
        current = hmac_sha512(password, &current);
        for (byte, mixed) in out.iter_mut().zip(current) {
            *byte ^= mixed;
        }
    }
    salted.fill(0);
    current.fill(0);
    std::hint::black_box((&mut salted, &mut current));
    out
}

fn hmac_sha512(key: &[u8], message: &[u8]) -> [u8; 64] {
    let mut mac =
        <Hmac<Sha512> as Mac>::new_from_slice(key).expect("HMAC takes a key of any length");
    mac.update(message);
    mac.finalize().into_bytes().into()
}

/// Where an Ethereum account lives under a seed.
///
/// Not a setting. Every wallet an owner is likely to hold this phrase in —
/// MetaMask, Rabby, anything ethers builds — puts the first account here, so a
/// second path would be a way to derive an address the owner has never seen
/// while every screen still looked right. `defaultPath` in ethers' own
/// `hdwallet.ts` is this string.
const ETHEREUM_PATH: [u32; 5] = [44 | HARDENED, 60 | HARDENED, HARDENED, 0, 0];

/// BIP-32's hardened marker: the top bit of the index.
const HARDENED: u32 = 0x8000_0000;

/// Derive the account key at `m/44'/60'/0'/0/0`.
///
/// The 32 bytes it answers are a secp256k1 private key, and every use of them
/// in this app goes through `signing::MasterKey`, which will sign an enrolment
/// and nothing else.
pub fn ethereum_key(seed: &Seed) -> Result<[u8; 32], SeedError> {
    // The master key is an HMAC of the seed under a fixed string, which is what
    // makes a BIP-32 tree deterministic from the phrase alone.
    let mut wide = hmac_sha512(b"Bitcoin seed", seed.bytes());
    let mut key: [u8; 32] = wide[..32].try_into().expect("32 bytes");
    let mut chain: [u8; 32] = wide[32..].try_into().expect("32 bytes");
    for index in ETHEREUM_PATH {
        (key, chain) = child(&key, &chain, index)?;
    }
    wide.fill(0);
    chain.fill(0);
    std::hint::black_box((&mut wide, &mut chain));
    Ok(key)
}

/// One step down the tree.
///
/// The two cases differ in what goes into the HMAC and nothing else: a hardened
/// child commits to the *private* key, so knowing the parent's public key and
/// chain code is not enough to derive it; a normal child commits to the public
/// key, which is what lets a watch-only wallet walk the same branch. The path
/// above is hardened where the spec says an account should be.
fn child(key: &[u8; 32], chain: &[u8; 32], index: u32) -> Result<([u8; 32], [u8; 32]), SeedError> {
    let parent = k256::SecretKey::from_slice(key).map_err(|_| SeedError::Derivation)?;
    let mut message = Vec::with_capacity(37);
    if index & HARDENED == 0 {
        message.extend_from_slice(parent.public_key().to_sec1_bytes().as_ref());
    } else {
        message.push(0);
        message.extend_from_slice(key);
    }
    message.extend_from_slice(&index.to_be_bytes());

    let mut wide = hmac_sha512(chain, &message);
    let offset = k256::SecretKey::from_slice(&wide[..32]).map_err(|_| SeedError::Derivation)?;
    // The child key is the parent plus the HMAC's left half, in the scalar
    // field — and a sum that lands on zero is the one case the spec says to
    // refuse rather than use.
    let sum = *offset.to_nonzero_scalar().as_ref() + parent.to_nonzero_scalar().as_ref();
    let child = k256::SecretKey::new(sum.into())
        .to_bytes()
        .as_slice()
        .try_into()
        .map_err(|_| SeedError::Derivation)?;
    let chain: [u8; 32] = wide[32..].try_into().expect("32 bytes");

    message.fill(0);
    wide.fill(0);
    std::hint::black_box((&mut message, &mut wide));
    Ok((child, chain))
}

